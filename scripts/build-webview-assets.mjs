// Inlines marked + KaTeX (JS, CSS and woff2 fonts) into a TS module so the
// WebView renderer works fully offline. Runs on `postinstall`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const katexDir = join(root, 'node_modules/katex/dist');
const read = (p) => readFileSync(p, 'utf8');

let fontCount = 0;
const css = read(join(katexDir, 'katex.min.css')).replace(
  /src:url\(fonts\/([\w-]+)\.woff2\) format\("woff2"\)[^;}]*/g,
  (_, name) => {
    fontCount++;
    const b64 = readFileSync(join(katexDir, 'fonts', `${name}.woff2`)).toString('base64');
    return `src:url(data:font/woff2;base64,${b64}) format("woff2")`;
  },
);
if (fontCount === 0) throw new Error('No KaTeX fonts inlined: katex.min.css format changed');

const out = [
  '// GENERATED by scripts/build-webview-assets.mjs — do not edit.',
  `export const MARKED_JS = ${JSON.stringify(read(join(root, 'node_modules/marked/lib/marked.umd.js')))};`,
  `export const KATEX_JS = ${JSON.stringify(read(join(katexDir, 'katex.min.js')))};`,
  `export const KATEX_CSS = ${JSON.stringify(css)};`,
  '',
].join('\n');

writeFileSync(join(root, 'src/render/assets.generated.ts'), out);
console.log(`webview assets generated (${fontCount} fonts inlined)`);
